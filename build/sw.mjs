// Regenerates app/sw.js: the precache list and a bumped cache version.
//
//   node build/sw.mjs
//
// Replaces the sw.js half of build_tools.py. The list has to include everything a first
// load needs, which after the cutover means the renderer, the shared stylesheet and each
// module's data file as well as the pages. Precaching only the pages would leave a shell
// with nothing to render until that module had been opened online once.

import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const APP = join(ROOT, 'app');

const pages = readdirSync(APP).filter((f) => /\.html$/.test(f)).sort();
const moduleData = readdirSync(join(APP, 'data', 'modules')).filter((f) => f.endsWith('.js')).sort()
  .map((f) => `data/modules/${f}`);
const sharedData = readdirSync(join(APP, 'data')).filter((f) => f.endsWith('.js')).sort()
  .map((f) => `data/${f}`);

const shell = [
  ...pages,
  'bw.css', 'bw-renderer.js', 'facility.js',
  ...moduleData,
  ...sharedData,
  'manifest.json', 'builtwright_icon_192.png', 'builtwright_icon_512.png',
];

// Bump the version so installed devices fetch the new files.
const current = readFileSync(join(APP, 'sw.js'), 'utf8');
const prev = (current.match(/const CACHE='builtwright-v(\d+)-(\d+)'/) || [, '8', '0']);
const version = `builtwright-v${prev[1]}-${Number(prev[2]) + 1}`;

writeFileSync(join(APP, 'sw.js'), `// BuiltWright service worker: cache-first for the app shell, runtime cache for fonts and icon CSS
// Generated by build/sw.mjs, do not edit.
const CACHE='${version}';
const SHELL=${JSON.stringify(shell)};
self.addEventListener('install',e=>{e.waitUntil(caches.open(CACHE).then(c=>c.addAll(SHELL)).then(()=>self.skipWaiting()));});
self.addEventListener('activate',e=>{e.waitUntil(caches.keys().then(ks=>Promise.all(ks.filter(k=>k!==CACHE).map(k=>caches.delete(k)))).then(()=>self.clients.claim()));});
self.addEventListener('fetch',e=>{
  const u=new URL(e.request.url);
  if(e.request.method!=='GET') return;
  e.respondWith(caches.match(e.request,{ignoreSearch:true}).then(r=>r||fetch(e.request).then(res=>{
    if(res && res.ok && (u.origin===location.origin || /fonts\\.g|cdn\\.jsdelivr/.test(u.host))){ const cp=res.clone(); caches.open(CACHE).then(c=>c.put(e.request,cp)); }
    return res;
  }).catch(()=>caches.match('builtwright_diagnose_hub_v1.html'))));
});
`);
console.log(`sw.js: ${shell.length} shell entries (${pages.length} pages, ${moduleData.length} module data, ${sharedData.length} shared data), cache ${version}`);
